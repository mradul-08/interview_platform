function buildTree(depth = 5) {
  const nodes = [];
  const edges = [];
  const spacingX = 2.6;
  const spacingY = 1.85;

  function place(level, indexInLevel, count, parentIdx) {
    if (level > depth) return;
    const x = (indexInLevel - (count - 1) / 2) * (spacingX / Math.pow(1.55, level));
    const y = (depth / 2 - level) * spacingY;
    const z = (Math.random() - 0.5) * 1.4;
    const idx = nodes.length;
    nodes.push({ pos: [x, y, z], level });
    if (parentIdx !== null) edges.push([parentIdx, idx]);
    if (level < depth) {
      place(level + 1, indexInLevel * 2, count * 2, idx);
      place(level + 1, indexInLevel * 2 + 1, count * 2, idx);
    }
  }
  place(0, 0, 1, null);
  return { nodes, edges };
}

function GraphTree() {
  const groupRef = useRef();
  const { nodes, edges } = useMemo(() => buildTree(5), []);
  const pulses = useRef(
    Array.from({ length: 14 }, () => ({
      edge: edges[Math.floor(Math.random() * edges.length)],
      t: Math.random(),
      speed: 0.12 + Math.random() * 0.16,
    }))
  );
  const pulseRefs = useRef([]);

  useFrame((state, delta) => {
    if (groupRef.current) {
      groupRef.current.rotation.y += delta * 0.06;
      groupRef.current.rotation.x = Math.sin(state.clock.elapsedTime * 0.15) * 0.08;
    }
    pulses.current.forEach((p, i) => {
      p.t += delta * p.speed;
      if (p.t > 1) { p.t = 0; p.edge = edges[Math.floor(Math.random() * edges.length)]; }
      const mesh = pulseRefs.current[i];
      if (!mesh) return;
      const a = nodes[p.edge[0]].pos;
      const b = nodes[p.edge[1]].pos;
      mesh.position.set(a[0] + (b[0] - a[0]) * p.t, a[1] + (b[1] - a[1]) * p.t, a[2] + (b[2] - a[2]) * p.t);
      mesh.material.opacity = Math.sin(p.t * Math.PI);
    });
  });

  return (
    <group ref={groupRef} position={[1.6, -0.6, 0]} scale={1.2}>
      {edges.map(([a, b], i) => {
        const start = new THREE.Vector3(...nodes[a].pos);
        const end = new THREE.Vector3(...nodes[b].pos);
        const mid = start.clone().lerp(end, 0.5);
        const dir = end.clone().sub(start);
        const len = dir.length();
        const quat = new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 1, 0), dir.clone().normalize());
        return (
          <mesh key={i} position={mid} quaternion={quat}>
            <cylinderGeometry args={[0.012, 0.012, len, 6]} />
            <meshBasicMaterial color={EDGE_AMBER} transparent opacity={0.32} />
          </mesh>
        );
      })}
      {nodes.map((n, i) => {
        const c = NODE_COLORS[n.level % NODE_COLORS.length];
        return (
          <mesh key={i} position={n.pos}>
            <sphereGeometry args={[n.level === 0 ? 0.14 : 0.08 - n.level * 0.006, 16, 16]} />
            <meshStandardMaterial color={c} emissive={c} emissiveIntensity={0.6} roughness={0.35} />
          </mesh>
        );
      })}
      {pulses.current.map((_, i) => (
        <mesh key={`pulse-${i}`} ref={(el) => (pulseRefs.current[i] = el)}>
          <sphereGeometry args={[0.045, 8, 8]} />
          <meshBasicMaterial color="#fff7ea" transparent opacity={0} />
        </mesh>
      ))}
    </group>
  );
}

